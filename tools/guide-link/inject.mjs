// syed-guide injector — stamps a small "📖 Guide" link on each research site that opens that
// site's Throughline Guidebook (PDF). Links use the stable address
// https://throughline-guidebooks.vercel.app/guide/<slug>, which always redirects to the newest
// version, so nothing here changes when a book is corrected.
//
// HTML sites get an inline <script> between SYED-GUIDE markers (idempotent replace); Vite sites get
// src/guide.{ts,js} + an import after the entry file's last import. Re-run after editing:
//   node research-suite/tools/guide-link/inject.mjs
// Sits bottom-right; on sites that also have the ▶ Tour pill it stacks just above it.
import fs from 'fs';
import path from 'path';

const HOME = 'C:/Users/Syed Asrar';
const BASE = 'https://throughline-guidebooks.vercel.app/guide/';
const SITES = [
  { kind: 'html', file: 'research-suite/index.html', slug: 'hub', name: 'Throughline hub' },
  { kind: 'html', file: 'syeds-research-book/index.html', slug: 'book', name: "Syed's Research Book", tour: true },
  { kind: 'html', file: 'journaltime/index.html', slug: 'jt', name: 'JournalTime', tour: true },
  { kind: 'vite', entry: 'paperpulse/src/main.tsx', out: 'paperpulse/src/guide.ts', slug: 'pc', name: 'PaperCards' },
  { kind: 'vite', entry: 'researchflow/src/main.tsx', out: 'researchflow/src/guide.ts', slug: 'rf', name: 'ResearchFlow', tour: true },
  { kind: 'vite', entry: 'theoryscope/src/main.tsx', out: 'theoryscope/src/guide.ts', slug: 'ts', name: 'TheoryScope', tour: true },
  { kind: 'vite', entry: 'scalebase/client/src/main.tsx', out: 'scalebase/client/src/guide.ts', slug: 'ss', name: 'ScaleScope', tour: true },
  { kind: 'vite', entry: 'toolsscope/src/main.tsx', out: 'toolsscope/src/guide.ts', slug: 'to', name: 'ToolsScope', tour: true },
  { kind: 'vite', entry: 'throughline-studio/src/main.tsx', out: 'throughline-studio/src/guide.ts', slug: 'studio', name: 'Throughline Studio' },
];

const snippet = ({ slug, name, tour }) => `(function () {
  var HREF = '${BASE}${slug}', NAME = ${JSON.stringify(name)};
  function init() {
    if (!document.body || document.getElementById('syed-guide-link')) return;
    var a = document.createElement('a');
    a.id = 'syed-guide-link';
    a.href = HREF; a.target = '_blank'; a.rel = 'noopener';
    a.setAttribute('aria-label', 'Read the ' + NAME + ' guidebook (PDF, opens in a new tab)');
    a.title = 'The ' + NAME + ' guidebook — how to use this site (PDF)';
    a.style.cssText = 'position:fixed;right:18px;bottom:${tour ? '64px' : '18px'};z-index:9000;display:inline-flex;align-items:center;gap:7px;padding:8px 14px;border-radius:999px;border:1px solid rgba(203,184,232,.4);background:rgba(21,16,31,.88);color:#f3eefc;font:600 13px/1 "Plus Jakarta Sans",system-ui,sans-serif;text-decoration:none;-webkit-backdrop-filter:blur(10px);backdrop-filter:blur(10px);box-shadow:0 4px 18px rgba(0,0,0,.35)';
    a.innerHTML = '<span aria-hidden="true" style="font-size:13px;line-height:1">\\u{1F4D6}</span><span>Guide</span>';
    document.body.appendChild(a);
  }
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', init); else init();
  // SPA re-renders can replace <body> children; re-add if it disappears
  new MutationObserver(function () { if (!document.getElementById('syed-guide-link')) init(); }).observe(document.documentElement, { childList: true, subtree: false });
  window.addEventListener('beforeprint', function () { var e = document.getElementById('syed-guide-link'); if (e) e.style.display = 'none'; });
  window.addEventListener('afterprint', function () { var e = document.getElementById('syed-guide-link'); if (e) e.style.display = ''; });
})();`;

const OPEN = '<!-- SYED-GUIDE (generated by research-suite/tools/guide-link/inject.mjs - edit there) -->';
const CLOSE = '<!-- /SYED-GUIDE -->';
const reEsc = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
for (const s of SITES) {
  if (s.kind === 'html') {
    const f = path.join(HOME, s.file);
    let html = fs.readFileSync(f, 'utf8');
    const block = `${OPEN}\n<script>\n${snippet(s)}\n</script>\n${CLOSE}`;
    const re = new RegExp(`${reEsc(OPEN)}[\\s\\S]*?${reEsc(CLOSE)}`);
    if (re.test(html)) html = html.replace(re, block);
    else { const i = html.lastIndexOf('</body>'); if (i < 0) throw new Error(s.file + ': no </body>'); html = html.slice(0, i) + block + '\n' + html.slice(i); }
    fs.writeFileSync(f, html);
  } else {
    fs.writeFileSync(path.join(HOME, s.out), `// syed-guide — "📖 Guide" link to this site's Throughline Guidebook (generated by\n// research-suite/tools/guide-link/inject.mjs — edit there, then re-run).\n${snippet(s)}\nexport {};\n`);
    const ef = path.join(HOME, s.entry);
    let entry = fs.readFileSync(ef, 'utf8');
    if (!/import ['"]\.\/guide['"]/.test(entry)) {
      const lines = entry.split('\n');
      const last = lines.reduce((k, l, i) => (/^import\s/.test(l) ? i : k), -1);
      lines.splice(last + 1, 0, "import './guide'");
      fs.writeFileSync(ef, lines.join('\n'));
    }
  }
  console.log(`${s.kind.padEnd(4)} ${s.slug.padEnd(6)} → ${BASE}${s.slug}`);
}
